-- =============================================================================
-- PART 1: CREATE BACKUP TABLES BEFORE RUNNING THE BATCH JOB
-- (Backs up all 14 tables that are written/modified/deleted by icnCsrToMccaJob)
-- =============================================================================

-- 1. Core ICN/CSR & Claim Main Tables (Modified in Steps 2, 3, 4, 5, 6, 7, 8, 9, updateRptdColumn)
CREATE TABLE IF NOT EXISTS MCCA_ICN_BKP_BATCH                     AS SELECT * FROM MCCA_ICN;
CREATE TABLE IF NOT EXISTS MCCA_CSR_BKP_BATCH                     AS SELECT * FROM MCCA_CSR;
CREATE TABLE IF NOT EXISTS MCCA_CLAIM_BKP_BATCH                   AS SELECT * FROM MCCA_CLAIM;
CREATE TABLE IF NOT EXISTS MCCA_OTHR_INJ_CLMTS_PYMT_BKP_BATCH     AS SELECT * FROM MCCA_OTHR_INJ_CLMTS_PYMT;
CREATE TABLE IF NOT EXISTS MCCA_PROJECTIONS_BKP_BATCH             AS SELECT * FROM MCCA_PROJECTIONS;

-- 2. Staging / Temp Tables (Read in Steps 1, 3, 4, 5 and DELETED in Step 10 during Monthly run!)
CREATE TABLE IF NOT EXISTS MCCA_TMP_CLM_BKP_BATCH                 AS SELECT * FROM MCCA_TMP_CLM;
CREATE TABLE IF NOT EXISTS MCCA_TMP_CLMNT_BKP_BATCH               AS SELECT * FROM MCCA_TMP_CLMNT;

-- 3. IPM-to-FACTS Conversion Mapping & Version Tables (Modified in Step 1)
CREATE TABLE IF NOT EXISTS IPM_FACTS_CLAIM_MAPPING_BKP_BATCH      AS SELECT * FROM IPM_FACTS_CLAIM_MAPPING_TABLE;
CREATE TABLE IF NOT EXISTS IPM_FACTS_CLID_MAPPING_BKP_BATCH       AS SELECT * FROM IPM_FACTS_CLID_MAPPING_TABLE;
CREATE TABLE IF NOT EXISTS MCCA_CODES_DECODE_BKP_BATCH            AS SELECT * FROM MCCA_CODES_DECODE;

-- 4. Downstream Tables Updated ONLY if Step 1 finds new IPM-to-FACTS converted claims
CREATE TABLE IF NOT EXISTS MCCA_RFR_BKP_BATCH                     AS SELECT * FROM MCCA_RFR;
CREATE TABLE IF NOT EXISTS MCCA_RFR_PAYLOG_BKP_BATCH              AS SELECT * FROM MCCA_RFR_PAYLOG;
CREATE TABLE IF NOT EXISTS MCCA_RFR_PAYLOG_CPT_BKP_BATCH          AS SELECT * FROM MCCA_RFR_PAYLOG_CPT;
CREATE TABLE IF NOT EXISTS MCCA_REMARKS_BKP_BATCH                 AS SELECT * FROM MCCA_REMARKS;
CREATE TABLE IF NOT EXISTS MCCA_WRITE_OFF_BKP_BATCH               AS SELECT * FROM MCCA_WRITE_OFF;


-- =============================================================================
-- PART 2: COMPARE ROW COUNTS (BEFORE vs. AFTER BATCH RUN)
-- =============================================================================
SELECT 'MCCA_ICN' AS table_name,
       (SELECT COUNT(*) FROM MCCA_ICN_BKP_BATCH) AS before_count,
       (SELECT COUNT(*) FROM MCCA_ICN)     AS after_count
UNION ALL
SELECT 'MCCA_CSR',
       (SELECT COUNT(*) FROM MCCA_CSR_BKP_BATCH),
       (SELECT COUNT(*) FROM MCCA_CSR)
UNION ALL
SELECT 'MCCA_CLAIM',
       (SELECT COUNT(*) FROM MCCA_CLAIM_BKP_BATCH),
       (SELECT COUNT(*) FROM MCCA_CLAIM)
UNION ALL
SELECT 'MCCA_OTHR_INJ_CLMTS_PYMT',
       (SELECT COUNT(*) FROM MCCA_OTHR_INJ_CLMTS_PYMT_BKP_BATCH),
       (SELECT COUNT(*) FROM MCCA_OTHR_INJ_CLMTS_PYMT)
UNION ALL
SELECT 'MCCA_PROJECTIONS',
       (SELECT COUNT(*) FROM MCCA_PROJECTIONS_BKP_BATCH),
       (SELECT COUNT(*) FROM MCCA_PROJECTIONS)
UNION ALL
SELECT 'MCCA_TMP_CLM',
       (SELECT COUNT(*) FROM MCCA_TMP_CLM_BKP_BATCH),
       (SELECT COUNT(*) FROM MCCA_TMP_CLM)
UNION ALL
SELECT 'MCCA_TMP_CLMNT',
       (SELECT COUNT(*) FROM MCCA_TMP_CLMNT_BKP_BATCH),
       (SELECT COUNT(*) FROM MCCA_TMP_CLMNT);


